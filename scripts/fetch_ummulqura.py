#!/usr/bin/env python3
"""
Fetch Saudi Arabia's prayer times from KACST, which publishes the official
Umm al-Qura calendar (ummulqura.org.sa).

KACST lists 173 official cities and governorates with coordinates
(sources/ummulqura/cities.json, from ummulqura.org.sa/assets/data/cities.json);
its API computes the authority's times for a point, so we ask it only for
those official points. Each one is a zone (SA{id}).

KACST publishes fajr, sunrise, dhuhr, asr, maghrib and isha (Ramadan isha
included). There's no separate imsak: the fast starts at fajr, so imsak =
fajr (as for the UAE and Turkey).

Usage:
  python3 scripts/fetch_ummulqura.py [year ...]   # this year and next by default
  python3 scripts/fetch_ummulqura.py --zones      # (re)generate data/zones/SA.yaml
"""

import json
import os
import sys
import time
from datetime import datetime
from urllib.request import Request, urlopen

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from utils import month_complete  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CITIES = os.path.join(ROOT, "sources", "ummulqura", "cities.json")
API = ("https://umqserv.kacst.gov.sa/api/v1/Prayer/GetPrayerByYear"
       "?lang=en&format=24&yg={y}&lat={lat}&lon={lng}&zone=3")
REGIONS = {
    1001: "Riyadh", 1002: "Makkah", 1003: "Madinah", 1004: "Qassim",
    1005: "Eastern Province", 1006: "Asir", 1007: "Tabuk", 1008: "Hail",
    1009: "Northern Borders", 1010: "Jazan", 1011: "Najran", 1012: "Al Bahah",
    1013: "Al Jouf",
}


def cities():
    return json.load(open(CITIES, encoding="utf-8"))


def fetch_year(city, y):
    for attempt in range(4):
        try:
            req = Request(API.format(y=y, lat=city["latitude"], lng=city["longitude"]),
                          headers={"User-Agent": "simplesolat-data"})
            with urlopen(req, timeout=60) as resp:
                days = json.loads(resp.read())
            break
        except Exception:
            if attempt == 3:
                raise
            time.sleep(3 * (attempt + 1))
    months = {}
    for d in days:
        g, p = d["gregorianDate"], d["prayerTimes"]
        months.setdefault(g["month"], []).append({
            "date": f"{g['year']}-{g['month']:02d}-{g['day']:02d}",
            "imsak": p["fajr"], "fajr": p["fajr"], "syuruk": p["sunrise"],
            "dhuhr": p["dhuhr"], "asr": p["asr"], "maghrib": p["maghrib"], "isha": p["isha"],
        })
    return months


def fetch(years):
    written = skipped = 0
    for city in cities():
        zone = f"SA{city['id']}"
        out_dir = os.path.join(ROOT, "data", "prayer-times", "SA", zone)
        for y in years:
            paths = {m: os.path.join(out_dir, f"{y}-{m:02d}.json") for m in range(1, 13)}
            if all(month_complete(p, str(y), f"{m:02d}") for m, p in paths.items()):
                skipped += 12
                continue
            months = fetch_year(city, y)
            os.makedirs(out_dir, exist_ok=True)
            for m, path in paths.items():
                with open(path, "w", encoding="utf-8") as f:
                    json.dump(sorted(months[m], key=lambda r: r["date"]), f, indent=2)
                    f.write("\n")
                written += 1
            time.sleep(0.3)
    print(f"Done: {written} files written, {skipped} skipped")


def emit_zones():
    lines = [
        "# Saudi Arabia (KACST, Umm al-Qura): the official cities and governorates.",
        "# Generated by scripts/fetch_ummulqura.py --zones from sources/ummulqura/cities.json;",
        "# shapes from scripts/patch_sa_zones.py (each city's nearest-city area).",
        "zones:",
    ]
    for c in sorted(cities(), key=lambda c: c["id"]):
        lines += [
            f"  - code: SA{c['id']}",
            "    country: SA",
            f"    state: {REGIONS[c['region_id']]}",
            f"    location: {c['name_en']}",
            "    timezone: Asia/Riyadh",
            "    shapes:",
            f"      - {c['name_en']}",
            "",
        ]
    out = os.path.join(ROOT, "data", "zones", "SA.yaml")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {out}")


def main():
    if "--zones" in sys.argv[1:]:
        emit_zones()
        return
    now = datetime.now()
    fetch([int(a) for a in sys.argv[1:]] or [now.year, now.year + 1])


if __name__ == "__main__":
    main()
